const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const assert = require('node:assert/strict');
const {webcrypto} = require('node:crypto');
const root = path.join(__dirname, '..');
let view;
function Vue(options) { view = options; }
Vue.set = (object, key, value) => { object[key] = value; };
const sandbox = {Vue, console, window: {crypto: webcrypto, setTimeout() {}}, moment: value => ({valueOf: () => value})};
vm.createContext(sandbox);
for (const file of ['web/assets/js/util/common.js', 'web/assets/js/util/utils.js', 'web/assets/js/model/xray.js', 'web/assets/js/model/models.js']) {
    vm.runInContext(fs.readFileSync(path.join(root, file), 'utf8'), sandbox);
}
const html = fs.readFileSync(path.join(root, 'web/html/xui/inbound_modal.html'), 'utf8');
vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1] + '\nthis.modal=inModal; this.InboundModel=Inbound;', sandbox);
const modal = sandbox.modal;
const fixture = new sandbox.InboundModel();
fixture.stream.network = 'tcp';
fixture.stream.security = 'none';
const form = fs.readFileSync(path.join(root, 'web/html/xui/form/inbound.html'), 'utf8');
const transport = [...form.matchAll(/<section\b([^>]*)>([\s\S]*?)<\/section>/g)].find(section=>section[2].includes('<h3>传输配置</h3>'));
assert.ok(transport && transport[2].includes('{{template "form/streamSettings"}}'));
const transportCondition=transport[1].match(/v-if="([^"]+)"/)[1];
fixture.stream.security='reality';
assert.equal(vm.runInNewContext(transportCondition,{inbound:fixture}),true,'REALITY must retain transport controls inside advanced settings');
fixture.stream.security='none';
modal.show({title:'编辑入站',okText:'确定',inbound:fixture,editingId:2});
assert.equal(modal.title, '编辑入口');
assert.equal(modal.okText, '保存');
assert.equal(modal.advancedOpen, false);
for (const [security, label] of [['none','安全设置'],['tls','TLS 安全'],['reality','REALITY 安全'],['xtls','XTLS 安全']]) {
    modal.inbound.stream.security=security;
    assert.equal(view.computed.securitySectionTitle(),label);
}
modal.dbInbound.externalHost='entry.example.test';
modal.dbInbound.externalPort=443;
modal.dbInbound.externalTls=true;
modal.inbound.stream.network='xhttp';
modal.inbound.stream.security='none';
assert.equal(view.computed.securitySectionTitle(),'TLS 安全','managed TLS belongs to the public entry, not the internal listener');
modal.show({inbound:fixture,editingId:2});
const original = modal.stateSignature();
modal.advancedOpen=true;
assert.equal(modal.stateSignature(),original,'opening advanced settings must not alter connection data');
assert.equal(modal.isDirty(),false);
modal.close();
assert.equal(modal.advancedOpen,false);
modal.show({inbound:fixture,editingId:2});
modal.inbound.stream.security='reality';
modal.inbound.stream.reality={serverNames:['example.test'],dest:'example.test:443',privateKey:'preserved-key',shortIds:['abc']};
let saves=0;
modal.confirm=()=>{saves++;};
modal.ok();
assert.equal(saves,0);
assert.match(modal.validationError,/Short ID/);
assert.equal(modal.advancedOpen,true,'a hidden invalid parameter must reveal its controls');
assert.equal(modal.inbound.stream.reality.privateKey,'preserved-key');
assert.equal(modal.inbound.stream.reality.shortIds[0],'abc','validation cannot silently replace existing settings');
modal.inbound.stream.reality.shortIds=['abcd'];
modal.ok();
assert.equal(saves,1,'the same retained form can recover after correction');
modal.close();
modal.show({inbound:fixture,editingId:2});
modal.inbound.port=0;
modal.ok();
assert.match(modal.validationError,/端口/);
assert.equal(modal.advancedOpen,false,'basic validation should keep unrelated technical controls collapsed');
console.log('PASS: entry naming, actual security titles, managed public TLS, advanced disclosure state, hidden validation recovery and unchanged connection data');
